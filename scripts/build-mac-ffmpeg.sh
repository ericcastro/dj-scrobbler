#!/bin/bash
set -euo pipefail

archive="$1"
arch="$2"
output="$3"
case "$arch" in
  arm64) target=arm64 ;;
  x64) target=x86_64 ;;
  *) echo "Unsupported macOS FFmpeg architecture: $arch" >&2; exit 1 ;;
esac

work_dir="$(mktemp -d /private/tmp/dj-scrobbler-ffmpeg.XXXXXX)"
trap 'rm -rf "$work_dir"' EXIT
tar -xf "$archive" -C "$work_dir" --strip-components=1
cd "$work_dir"

# Build only upstream LGPL code and Apple system frameworks. Autodetection is
# disabled so libraries installed on a developer/CI host cannot change licensing.
./configure \
  --disable-autodetect --disable-gpl --disable-nonfree --disable-version3 \
  --disable-doc --disable-debug --disable-ffplay --disable-ffprobe \
  --enable-static --disable-shared --disable-x86asm \
  --enable-cross-compile --target-os=darwin --arch="$target" \
  --cc="$(xcrun --find clang)" \
  --sysroot="$(xcrun --show-sdk-path)" \
  --extra-cflags="-arch $target -mmacosx-version-min=11.0" \
  --extra-ldflags="-arch $target -mmacosx-version-min=11.0" \
  --enable-videotoolbox --enable-audiotoolbox --enable-securetransport || {
    tail -60 ffbuild/config.log >&2
    exit 1
  }

# This is generated by configure, including for a cross-compiled Intel build
# that cannot execute on the host without Rosetta.
if ! /usr/bin/grep -q '^#define FFMPEG_LICENSE "LGPL version 2.1 or later"' config.h; then
  echo 'Refusing to package FFmpeg with an unexpected license configuration.' >&2
  exit 1
fi
jobs="$(sysctl -n hw.logicalcpu 2>/dev/null || echo 2)"
if (( jobs > 8 )); then jobs=8; fi
make -j "$jobs" ffmpeg
mkdir -p "$(dirname "$output")"
cp ffmpeg "$output"
chmod +x "$output"
